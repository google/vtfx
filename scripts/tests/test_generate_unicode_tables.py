class GenerateUnicodeTablesTest(unittest.TestCase):
    def setUp(self):
        self.root = pathlib.Path(self.enterContext(tempfile.TemporaryDirectory()))
        self.ucd = self.root / "ucd"
        self.output = self.root / "out" / "UnicodeWidthTables.kt"
        self.ignorables_output = self.root / "out" / "UnicodeDefaultIgnorables.kt"
        self.diacritics_output = self.root / "out" / "PlaceholderDiacritics.kt"
        self.write("ucd/EastAsianWidth.txt", EAST_ASIAN_WIDTH)
        self.write("ucd/extracted/DerivedGeneralCategory.txt", DERIVED_GENERAL_CATEGORY)
        self.write("ucd/DerivedCoreProperties.txt", DERIVED_CORE_PROPERTIES)
        self.write("ucd/extracted/DerivedCombiningClass.txt", DERIVED_COMBINING_CLASS)
        self.write("ucd/extracted/DerivedDecompositionType.txt", DERIVED_DECOMPOSITION_TYPE)
        self.write("ucd/DerivedAge.txt", DERIVED_AGE)

    def write(self, path, content):
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content, encoding="utf-8")

    def run_script(self, *args):
        return subprocess.run(
            [sys.executable, "-I", str(SCRIPT), "--ucd", str(self.ucd), "--output", str(self.output),
             "--ignorables-output", str(self.ignorables_output),
             "--diacritics-output", str(self.diacritics_output), *args],
            capture_output=True, text=True)

    def generated_tables(self, output=None):
        """Returns the generated source after its license header."""
        source = (output or self.output).read_text(encoding="utf-8")
        self.assertTrue(source.startswith("/*\n * Copyright 2026 Google LLC\n"), source[:100])
        return source[source.index(" */\n\n") + len(" */\n\n"):]

    def test_generates_tables_by_the_rules(self):
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.generated_tables(), EXPECTED_TABLES)

    def test_generates_the_default_ignorables_merged(self):
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.generated_tables(self.ignorables_output), EXPECTED_IGNORABLES)

    def test_generates_the_diacritics_of_placeholders_by_kittys_rule(self):
        result = self.run_script()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.generated_tables(self.diacritics_output), EXPECTED_DIACRITICS)

    def test_rejects_ages_of_another_version(self):
        self.write("ucd/DerivedAge.txt", DERIVED_AGE.replace("16.0.0", "17.0.0"))
        result = self.run_script()
        self.assertEqual(result.returncode, 2)
        self.assertIn("EastAsianWidth.txt is Unicode 16.0.0, but DerivedAge.txt is Unicode 17.0.0", result.stderr)

    def test_check_passes_when_up_to_date(self):
        self.assertEqual(self.run_script().returncode, 0)
        result = self.run_script("--check")
        self.assertEqual(result.returncode, 0, result.stdout)

    def test_check_fails_when_out_of_date_and_writes_nothing(self):
        self.write("out/UnicodeWidthTables.kt", "stale\n")
        result = self.run_script("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("is not up to date", result.stdout)
        self.assertEqual(self.output.read_text(encoding="utf-8"), "stale\n")
        self.assertFalse(self.ignorables_output.exists())

    def test_check_fails_when_the_default_ignorables_are_out_of_date(self):
        self.assertEqual(self.run_script().returncode, 0)
        self.write("out/UnicodeDefaultIgnorables.kt", "stale\n")
        result = self.run_script("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("UnicodeDefaultIgnorables.kt is not up to date", result.stdout)
        self.assertEqual(self.ignorables_output.read_text(encoding="utf-8"), "stale\n")

    def test_check_fails_when_missing(self):
        result = self.run_script("--check")
        self.assertEqual(result.returncode, 1)
        self.assertFalse(self.output.exists())

    def test_rejects_files_of_different_versions(self):
        self.write(
            "ucd/extracted/DerivedGeneralCategory.txt",
            DERIVED_GENERAL_CATEGORY.replace("16.0.0", "17.0.0"))
        result = self.run_script()
        self.assertEqual(result.returncode, 2)
        self.assertIn("EastAsianWidth.txt is Unicode 16.0.0, but DerivedGeneralCategory.txt is Unicode 17.0.0",
                      result.stderr)

    def test_rejects_core_properties_of_another_version(self):
        self.write("ucd/DerivedCoreProperties.txt", DERIVED_CORE_PROPERTIES.replace("16.0.0", "17.0.0"))
        result = self.run_script()
        self.assertEqual(result.returncode, 2)
        self.assertIn("EastAsianWidth.txt is Unicode 16.0.0, but DerivedCoreProperties.txt is Unicode 17.0.0",
                      result.stderr)
        self.assertFalse(self.output.exists())

    def test_rejects_a_file_without_its_version(self):
        self.write("ucd/EastAsianWidth.txt", "# Some other file\n")
        result = self.run_script()
        self.assertEqual(result.returncode, 2)
        self.assertIn("The first line of EastAsianWidth.txt does not name its version", result.stderr)


if __name__ == "__main__":
    unittest.main()
