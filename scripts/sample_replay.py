"""Replays the recordings of real apps in the sample app on the emulator and takes screenshots.

The sample app shows the recorded output of real CLI apps (recordings/*.out), and of programs that
show images with the kitty graphics protocol (recordings/graphics). The screenshots go to
build/reports/sample-replay/, for a human to look at, with build/reports/sample-replay.md listing
them. vtfx-core's RecordingReplayTest checks the same
recordings against a reference terminal.

Usage: sample_replay.py [--serial SERIAL] [--skip-build]

Start the emulator with scripts/emulator.sh start first.
"""

import argparse
import datetime
import os
import subprocess
import time

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ADB_PATH = os.path.join(os.environ.get("ANDROID_HOME", os.path.expanduser("~/Android/Sdk")), "platform-tools", "adb")
ACTIVITY = "com.google.vtfx.sample/.MainActivity"
RECORDINGS = [
    "vim",
    "less",
    "htop",
    "tmux",
    "neovim",
    "emacs",
    "mc",
    "btop",
    "tig",
    "fzf",
    "ncdu",
    "timg",
    "icat",
    "icat-placeholder",
    "fastfetch",
]


def adb(serial, *args, binary=False):
    result = subprocess.run([ADB_PATH, "-s", serial, *args], capture_output=True, check=True)
    return result.stdout if binary else result.stdout.decode()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--serial", default=os.environ.get("ANDROID_SERIAL", "emulator-5580"))
    parser.add_argument("--skip-build", action="store_true")
    args = parser.parse_args()
    if not args.skip_build:
        subprocess.run([os.path.join(ROOT, "gradlew"), "--console=plain", "-q", ":vtfx-sample:assembleDebug"],
                       cwd=ROOT, check=True)
    apk = os.path.join(ROOT, "vtfx-sample", "build", "outputs", "apk", "debug", "vtfx-sample-debug.apk")
    adb(args.serial, "install", "-r", apk)
    out_dir = os.path.join(ROOT, "build", "reports", "sample-replay")
    os.makedirs(out_dir, exist_ok=True)
    for name in RECORDINGS:
        adb(args.serial, "shell", "am", "start", "-S", "-W", "-n", ACTIVITY)
        time.sleep(2)
        adb(args.serial, "shell", "input", "tap", "540", "900")
        time.sleep(2)
        adb(args.serial, "shell", "input", "text", f"replay%s{name}")
        adb(args.serial, "shell", "input", "keyevent", "KEYCODE_ENTER")
        time.sleep(3)
        with open(os.path.join(out_dir, f"{name}.png"), "wb") as f:
            f.write(adb(args.serial, "exec-out", "screencap", "-p", binary=True))
        print(f"{name}: done")
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    lines = [
        "# Replaying recordings in the sample app",
        "",
        "Generated by `scripts/sample_replay.py`. These are screens from running `replay <name>` in the sample app on the emulator. "
        "`RecordingReplayTest` checks that the characters and attributes match the reference terminal.",
        "",
        f"- Date (UTC): {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M')}",
        f"- Commit: {commit}",
        "",
    ]
    for name in RECORDINGS:
        lines += [f"## {name}", "", f"![{name}](sample-replay/{name}.png)", ""]
    with open(os.path.join(ROOT, "build", "reports", "sample-replay.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
