"""Runs the rendering end-to-end tests on an emulator and writes a report.

The instrumented tests of vtfx-compose (RenderConsistencyTest) draw the terminal with hardware
acceleration, as a device does, and check each cell against a software rendering of the same
terminal state. The result is for reporting, not a gate (docs/design/testing.md section 8): it
needs an emulator.

Usage: e2e_render.py [--serial SERIAL] [--report PATH]

Start the emulator with scripts/emulator.sh start first.
"""

import argparse
import datetime
import glob
import os
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ADB_PATH = os.path.join(os.environ.get("ANDROID_HOME", os.path.expanduser("~/Android/Sdk")), "platform-tools", "adb")
RESULTS = os.path.join(ROOT, "vtfx-compose", "build", "outputs", "androidTest-results", "connected", "debug")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--serial", default=os.environ.get("ANDROID_SERIAL", "emulator-5580"))
    parser.add_argument("--report", default=os.path.join(ROOT, "build", "reports", "e2e-render.md"))
    args = parser.parse_args()

    for old in glob.glob(os.path.join(RESULTS, "*.xml")):
        os.remove(old)
    env = dict(os.environ, ANDROID_SERIAL=args.serial)
    build = subprocess.run(
        [os.path.join(ROOT, "gradlew"), "--console=plain", "-q", ":vtfx-compose:connectedDebugAndroidTest"],
        cwd=ROOT, env=env, capture_output=True, text=True,
    )
    files = glob.glob(os.path.join(RESULTS, "*.xml"))
    if not files:
        print(build.stdout[-3000:], build.stderr[-3000:], sep="\n", file=sys.stderr)
        print("No test results; the build failed before the tests ran.", file=sys.stderr)
        return 1

    rows = []
    for path in sorted(files):
        for case in ET.parse(path).getroot().iter("testcase"):
            failure = case.find("failure")
            detail = ""
            if failure is not None:
                # The first line of the message, and the map of the cells that differ.
                text = (failure.text or failure.get("message") or "").strip()
                detail = text.split("\n\tat ")[0]
            rows.append((case.get("classname", "").rsplit(".", 1)[-1], case.get("name"), failure is None, detail))
    rows.sort(key=lambda row: (row[0], row[1]))

    android = subprocess.run([ADB_PATH, "-s", args.serial, "shell", "getprop", "ro.build.version.release"],
                             capture_output=True, text=True).stdout.strip()
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    passed = sum(1 for row in rows if row[2])
    lines = [
        "# Rendering e2e results",
        "",
        "Generated by `scripts/e2e_render.py`. Do not edit by hand. It draws with hardware acceleration on the emulator, and "
        "compares each cell with a reference drawing of the same terminal state in software (`RenderConsistencyTest` in `vtfx-compose`). "
        "For reports, not a gate (section 8 of testing.md).",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Date (UTC) | {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M')} |",
        f"| Commit | {commit} |",
        f"| Android | {android or 'unknown'} |",
        f"| Result | {passed} passed, {len(rows) - passed} failed |",
        "",
        "| Test | Result |",
        "|---|---|",
    ]
    lines += [f"| {cls}.{name} | {'pass' if ok else 'fail'} |" for cls, name, ok, _ in rows]
    failures = [row for row in rows if not row[2]]
    if failures:
        lines += ["", "## Failures"]
        for cls, name, _, detail in failures:
            lines += ["", f"### {cls}.{name}", "", "```", detail, "```"]
    os.makedirs(os.path.dirname(args.report), exist_ok=True)
    with open(args.report, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"pass {passed}, fail {len(rows) - passed} -> {args.report}")
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
